import assert from 'node:assert/strict';
import { handleWorkshopMcp } from '../mcp/workshop-app.js';

const context={origin:'https://spider-paint.example',fetchText:async()=>''};
let id=0;
async function invoke(name,args={}){
  const r=await handleWorkshopMcp({jsonrpc:'2.0',id:++id,method:'tools/call',params:{name,arguments:args}},context);
  if(r.result.isError)return {error:JSON.parse(r.result.content[0].text).error};
  return r.result.structuredContent;
}
const opened=await invoke('open_workshop',{steps:[{tool:'add_box',args:{name:'table',size:[2,.2,1],at:[0,.1,0]}}]});
const sid=opened.session_id;
assert.match(sid,/^[0-9a-f]{40}$/);
let state=await invoke('workshop_state',{session_id:sid});
assert.equal(state.ready,false);
assert.equal(state.revision,0);
const table={name:'table',mesh:{positions:[[0,0,0],[2,0,0],[2,1,0]],faces:[{v:[0,1,2],color:'#ccc'}]}};
const scene={format:'3draft-scene',version:1,objects:[table]};
let reply=await invoke('workshop_publish',{session_id:sid,revision:0,scene});
assert.equal(reply.revision,1);
state=await invoke('workshop_state',{session_id:sid,include_scene:true});
assert.equal(state.ready,true);
assert.equal(state.object_count,1);
assert.equal(state.objects[0].name,'table');
assert.deepEqual(state.scene.objects[0].mesh,table.mesh);
let edit=await invoke('workshop_edit',{session_id:sid,revision:1,steps:[{tool:'add_box',args:{name:'spider',size:[.4,.2,.5],at:[0,.5,0]}}]});
assert.equal(edit.status,'queued');
let poll=await invoke('workshop_poll',{session_id:sid});
assert.equal(poll.pending.batch_id,edit.batch_id);
assert.equal(poll.pending.steps[0].args.name,'spider');
const conflict=await invoke('workshop_publish',{session_id:sid,revision:1,scene});
assert.equal(conflict.error,'workshop_edit_pending');
const stale=await invoke('workshop_edit',{session_id:sid,revision:0,steps:[{tool:'list'}]});
assert.equal(stale.error,'workshop_edit_already_pending');
const spider={name:'spider',mesh:{positions:[[0,0,0],[1,0,0],[0,1,0]],faces:[{v:[0,1,2]}]}};
reply=await invoke('workshop_publish',{session_id:sid,revision:1,scene:{...scene,objects:[table,spider]},batch_id:edit.batch_id});
assert.equal(reply.revision,2);
state=await invoke('workshop_state',{session_id:sid});
assert.equal(state.object_count,2);
assert.equal(state.last_edit.status,'applied');
assert.equal(state.pending,null);
edit=await invoke('workshop_edit',{session_id:sid,revision:2,steps:[{tool:'remove',args:{name:'missing'}}]});
const failed=await invoke('workshop_reject',{session_id:sid,batch_id:edit.batch_id,reason:'no object'});
assert.equal(failed.status,'failed');
state=await invoke('workshop_state',{session_id:sid});
assert.equal(state.revision,2,'rejected batches do not mutate the scene');
assert.equal(state.pending,null);
const stalePublish=await invoke('workshop_publish',{session_id:sid,revision:1,scene});
assert.equal(stalePublish.error,'workshop_revision_conflict');
const missing=await invoke('workshop_state',{session_id:'0'.repeat(40)});
assert.equal(missing.error,'workshop_session_not_found');
console.log('Capability session, native snapshot, queued agent edit, CAS and failure recovery: OK');
